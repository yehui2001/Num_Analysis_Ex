function z=f_Bis(f,a,b,accurate)
p=(a+b)/2;
n=0;
z=0;
while (abs(f(p)-0)>accurate) 
    if(f(p)==0)
        z=p;
        break;
    end
    if(f(a)==0)
        z=a;
        break;
    end
    if(f(b)==0)
        z=b;
        break;
    end
    if(f(a)*f(p)<0)
        b=p;
        p=(a+b)/2;
    else
        a=p;
        p=(a+b)/2;
    end
    z=p;
    n=n+1;
end
n;
end