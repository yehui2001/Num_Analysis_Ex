clc;
clear;
%对上下两段插值
x_i=-3:0.5:3;
y1=(25-x_i.^2).^(1/2);
y2=-(25-x_i.^2).^(1/2);
xx_i=-3:0.1:3;
yy1=spline(x_i,y1,xx_i);
yy2=spline(x_i,y2,xx_i);
%对左右两段插值
y_i=-4:0.5:4;
x1=(25-y_i.^2).^(1/2);
x2=-(25-y_i.^2).^(1/2);
yy_i=-4:0.1:4;
xx1=spline(y_i,x1,yy_i);
xx2=spline(y_i,x2,yy_i);
%画出图像
plot(xx_i,yy1,xx_i,yy2,xx1,yy_i,xx2,yy_i);